"""Erzeugt die synthetischen Demo-Daten (demo_temperature_v1) und kleine Fehler-Fixtures.

Synthetisch, keine Messwerte: Die Zahlen stammen aus einem einfachen Modell mit festem Seed.
Nur die Modellparameter sind an der NASA-POWER-Klimatologie 1991-2020 (T2M) für die beiden
Katalog-Gitterpunkte ausgerichtet; NASA ist nicht die Quelle dieser Zahlen.

Modell pro Monat (Einheit degC):
    T(y, m) = mean_1991_2020
              - half_amplitude * cos(2*pi*(m - 1) / 12)        # Januar Minimum, Juli Maximum
              + trend_per_decade / 10 * (y + (m - 0.5) / 12 - 2006.0)  # um Baseline-Mitte zentriert
              + a(y)                                           # jährliches AR(1)-Rauschen
              + e(y, m)                                        # monatliches weißes Rauschen
    a(y) = phi * a(y - 1) + sqrt(1 - phi^2) * annual_sd * N(0, 1), a(1981) ~ N(0, annual_sd)
    e(y, m) ~ N(0, monthly_sd)

annual_sd ist so gewählt, dass die SD der Jahresmittel-Residuen (AR(1) plus gemitteltes
Monatsrauschen) ungefähr der Referenz entspricht: annual_sd = sqrt(residual_sd^2 - monthly_sd^2/12).

Ausgabe ist byte-identisch bei wiederholtem Lauf: feste Seeds, Rundung auf 2 Nachkommastellen,
sortierte Schlüssel, kein Zeitstempel, Zeilenende am Dateiende.

Aufruf (aus dem Repo-Root): uv run --project apps/api python scripts/generate_demo.py
Optional: --root PFAD schreibt dieselben relativen Pfade unter PFAD (für Tests).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Any

GENERATOR_VERSION = "1.0.0"
DATASET = "demo_temperature_v1"
PROVIDER = "synthetic"
VARIABLE_ID = "temperature_2m"
PARAMETER = "T2M"
UNIT = "degC"
FILL_VALUE = -999.0
START_YEAR = 1981
END_YEAR = 2025
BASELINE_START = 1991
BASELINE_END = 2020
# Mitte der Baseline 1991-2020 in Dezimaljahren (1991.0 bis 2021.0).
TREND_CENTER = 2006.0
DECIMALS = 2

REPO_ROOT = Path(__file__).resolve().parents[1]
DEMO_DIR = Path("data/demo")
FIXTURE_DIR = Path("apps/api/tests/fixtures/demo")
SERIES_FILE = DEMO_DIR / "temperature_monthly.json"
MANIFEST_FILE = Path("apps/api/tests/fixtures/demo_manifest.json")

SYNTHETIC_NOTICE = (
    "Synthetic demo data generated by a fixed-seed model. Not measurements and not NASA data. "
    "NASA POWER T2M climatology 1991-2020 was used only to choose model parameters."
)

REFERENCE = {
    "used_for": "choice of model parameters only; no values copied",
    "source": "NASA POWER monthly point API v2.10.0, parameter T2M, community RE (MERRA-2 grid)",
    "retrieved": "2026-11-14",
    "period": "1991-2020 climatology; trends from 1981-2025",
    "urls": {
        "vienna": (
            "https://power.larc.nasa.gov/api/temporal/monthly/point?parameters=T2M&community=RE"
            "&longitude=16.3738&latitude=48.2082&start=1981&end=2025&format=JSON"
        ),
        "madrid": (
            "https://power.larc.nasa.gov/api/temporal/monthly/point?parameters=T2M&community=RE"
            "&longitude=-3.7038&latitude=40.4168&start=1981&end=2025&format=JSON"
        ),
    },
}


@dataclass(frozen=True)
class SiteParams:
    location_id: str
    latitude: float
    longitude: float
    seed: int
    mean_1991_2020: float
    half_amplitude: float
    trend_per_decade: float
    residual_sd: float
    ar1_phi: float
    monthly_sd: float

    @property
    def annual_sd(self) -> float:
        return math.sqrt(self.residual_sd**2 - self.monthly_sd**2 / 12)


# Koordinaten wie im Katalog (schemas/catalog.py), Parameter laut Referenz (TD Recherche).
SITES: tuple[SiteParams, ...] = (
    SiteParams(
        location_id="vienna",
        latitude=48.21,
        longitude=16.37,
        seed=48211637,
        mean_1991_2020=9.40,
        half_amplitude=11.19,
        trend_per_decade=0.45,
        residual_sd=0.70,
        ar1_phi=0.15,
        monthly_sd=1.0,
    ),
    SiteParams(
        location_id="madrid",
        latitude=40.42,
        longitude=-3.70,
        seed=40420370,
        mean_1991_2020=13.24,
        half_amplitude=10.74,
        trend_per_decade=0.35,
        residual_sd=0.50,
        ar1_phi=0.0,
        monthly_sd=1.0,
    ),
)


def _r(value: float) -> float:
    # + 0.0 macht aus -0.0 eine 0.0, damit die Ausgabe stabil bleibt.
    return round(value, DECIMALS) + 0.0


def month_date(year: int, month: int) -> str:
    return f"{year:04d}-{month:02d}-01"


def generate_site(site: SiteParams) -> list[dict[str, Any]]:
    rng = random.Random(site.seed)
    annual_sd = site.annual_sd
    innovation_sd = math.sqrt(1 - site.ar1_phi**2) * annual_sd
    observations: list[dict[str, Any]] = []
    a = rng.gauss(0.0, annual_sd)
    for year in range(START_YEAR, END_YEAR + 1):
        if year > START_YEAR:
            a = site.ar1_phi * a + rng.gauss(0.0, innovation_sd)
        for month in range(1, 13):
            t = year + (month - 0.5) / 12 - TREND_CENTER
            value = (
                site.mean_1991_2020
                - site.half_amplitude * math.cos(2 * math.pi * (month - 1) / 12)
                + site.trend_per_decade / 10 * t
                + a
                + rng.gauss(0.0, site.monthly_sd)
            )
            observations.append({"date": month_date(year, month), "value": _r(value)})
    return observations


def annual_means(observations: list[dict[str, Any]]) -> dict[int, float]:
    """Ungewichtete Mittel vollständiger Jahre (nur für Manifest und Tests)."""
    by_year: dict[int, list[float]] = {}
    for obs in observations:
        if obs["value"] is None:
            continue
        by_year.setdefault(int(obs["date"][:4]), []).append(float(obs["value"]))
    return {y: sum(v) / 12 for y, v in sorted(by_year.items()) if len(v) == 12}


def ols_slope_per_decade(means: dict[int, float]) -> float:
    years = list(means)
    n = len(years)
    x_mean = sum(years) / n
    y_mean = sum(means.values()) / n
    sxy = sum((x - x_mean) * (means[x] - y_mean) for x in years)
    sxx = sum((x - x_mean) ** 2 for x in years)
    return 10 * sxy / sxx


def _dump(data: Any) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _series_doc(
    series: list[dict[str, Any]], note: str, extra: dict[str, Any] | None = None
) -> dict[str, Any]:
    doc: dict[str, Any] = {
        "dataset": DATASET,
        "provider": PROVIDER,
        "synthetic": True,
        "notice": SYNTHETIC_NOTICE,
        "note": note,
        "variable_id": VARIABLE_ID,
        "parameter": PARAMETER,
        "unit": UNIT,
        "series": series,
    }
    if extra:
        doc.update(extra)
    return doc


def _site_entry(site: SiteParams, observations: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "location_id": site.location_id,
        "latitude": site.latitude,
        "longitude": site.longitude,
        "observations_monthly": observations,
    }


def build_fixtures(data: dict[str, list[dict[str, Any]]]) -> dict[str, dict[str, Any]]:
    """Kleine Fehler-Fixtures, abgeleitet aus der Wien-Reihe (gleiches Format wie die Demo)."""
    site = SITES[0]
    full = data[site.location_id]

    def year_of(obs: dict[str, Any]) -> int:
        return int(obs["date"][:4])

    gap_dates = {"2003-06-01", "2003-07-01", "2003-08-01", "2010-01-01"}
    gap = [{**o, "value": None} if o["date"] in gap_dates else dict(o) for o in full]

    fill_dates = {"1995-02-01", "2012-11-01", "2018-07-01"}
    fill = [{**o, "value": FILL_VALUE} if o["date"] in fill_dates else dict(o) for o in full]

    incomplete = [dict(o) for o in full if not (year_of(o) == 2025 and o["date"] > "2025-06-01")]

    twenty = [dict(o) for o in full if year_of(o) >= 2006]

    no_baseline = [
        {**o, "value": None} if BASELINE_START <= year_of(o) <= BASELINE_END else dict(o)
        for o in full
    ]

    return {
        "series_gap.json": _series_doc(
            [_site_entry(site, gap)],
            "Gap: values missing (null) for 2003-06..2003-08 and 2010-01.",
            {"case": "gap", "missing_dates": sorted(gap_dates)},
        ),
        "series_fill_values.json": _series_doc(
            [_site_entry(site, fill)],
            "Raw provider fill values (-999.0) not yet normalised; must become null, never 0.",
            {"case": "fill_values", "fill_value": FILL_VALUE, "fill_dates": sorted(fill_dates)},
        ),
        "series_incomplete_year.json": _series_doc(
            [_site_entry(site, incomplete)],
            "Incomplete last year: 2025 has only January to June.",
            {"case": "incomplete_year", "incomplete_year": 2025, "months_present": 6},
        ),
        "series_20_years.json": _series_doc(
            [_site_entry(site, twenty)],
            "Only 20 complete years (2006-2025): below the 30-year minimum for a trend.",
            {"case": "short_series", "start_year": 2006, "end_year": 2025},
        ),
        "series_no_baseline.json": _series_doc(
            [_site_entry(site, no_baseline)],
            "No baseline: every value in 1991-2020 is missing (null).",
            {"case": "missing_baseline", "baseline": {"start_year": 1991, "end_year": 2020}},
        ),
    }


def build_outputs() -> dict[Path, str]:
    data = {site.location_id: generate_site(site) for site in SITES}

    series_text = _dump(
        _series_doc(
            [_site_entry(site, data[site.location_id]) for site in SITES],
            "Monthly mean T2M-like values, one entry per month 1981-01 to 2025-12.",
            {"start": "1981-01", "end": "2025-12", "generator_version": GENERATOR_VERSION},
        )
    )

    locations = []
    for site in SITES:
        means = annual_means(data[site.location_id])
        baseline = [v for y, v in means.items() if BASELINE_START <= y <= BASELINE_END]
        locations.append(
            {
                "location_id": site.location_id,
                "latitude": site.latitude,
                "longitude": site.longitude,
                "seed": site.seed,
                "parameters": {
                    "mean_1991_2020_degC": site.mean_1991_2020,
                    "seasonal_half_amplitude_degC": site.half_amplitude,
                    "trend_per_decade_degC": site.trend_per_decade,
                    "annual_residual_sd_degC": site.residual_sd,
                    "annual_ar1_phi": site.ar1_phi,
                    "annual_ar1_sd_degC": _r(site.annual_sd),
                    "monthly_noise_sd_degC": site.monthly_sd,
                },
                "realised": {
                    "ols_trend_per_decade_degC_1981_2025": round(ols_slope_per_decade(means), 3),
                    "baseline_mean_1991_2020_degC": round(sum(baseline) / len(baseline), 3),
                    "note": "Unweighted annual means of the rounded monthly values.",
                },
            }
        )

    manifest = {
        "dataset": DATASET,
        "provider": PROVIDER,
        "synthetic": True,
        "notice": SYNTHETIC_NOTICE,
        "generator": {"path": "scripts/generate_demo.py", "version": GENERATOR_VERSION},
        "variable_id": VARIABLE_ID,
        "parameter": PARAMETER,
        "unit": UNIT,
        "period": {"start": "1981-01", "end": "2025-12"},
        "baseline": {"start_year": BASELINE_START, "end_year": BASELINE_END},
        "rounding_decimals": DECIMALS,
        "model": (
            "mean_1991_2020 - half_amplitude*cos(2*pi*(month-1)/12) "
            "+ trend_per_decade/10*(year + (month-0.5)/12 - 2006.0) "
            "+ annual AR(1) noise + monthly white noise; Python random.Random(seed).gauss"
        ),
        "locations": locations,
        "reference": REFERENCE,
        "files": {
            str(SERIES_FILE): {"sha256": hashlib.sha256(series_text.encode("utf-8")).hexdigest()}
        },
    }

    outputs: dict[Path, str] = {SERIES_FILE: series_text, MANIFEST_FILE: _dump(manifest)}
    for name, doc in build_fixtures(data).items():
        outputs[FIXTURE_DIR / name] = _dump(doc)
    return outputs


def write_outputs(root: Path) -> list[Path]:
    written = []
    for rel, text in build_outputs().items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        written.append(rel)
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="Zielwurzel (Standard: Repo)")
    args = parser.parse_args()
    for rel in write_outputs(args.root):
        print(f"geschrieben: {rel.as_posix()}")


if __name__ == "__main__":
    main()
